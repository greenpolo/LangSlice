def _literal_union(values: tuple[str, ...]) -> str:
    return " | ".join(f'"{value}"' for value in values)


def _extract_enum_values(
    bundle: dict[str, object],
    *,
    model_name: str,
    field_name: str,
) -> tuple[str, ...]:
    schemas = bundle["schemas"]
    assert isinstance(schemas, dict)
    schema = schemas[model_name]
    assert isinstance(schema, dict)
    properties = schema["properties"]
    assert isinstance(properties, dict)
    field_schema = properties[field_name]
    assert isinstance(field_schema, dict)

    enum_values: list[str] = []
    if isinstance(field_schema.get("enum"), list):
        enum_values = [str(value) for value in field_schema["enum"]]
    elif isinstance(field_schema.get("anyOf"), list):
        for option in field_schema["anyOf"]:
            if isinstance(option, dict) and isinstance(option.get("enum"), list):
                enum_values = [str(value) for value in option["enum"]]
                break

    if not enum_values:
        raise ValueError(f"No enum values found for {model_name}.{field_name}")
    return tuple(enum_values)


