def _write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _check_bundle_models(bundle: dict[str, object]) -> None:
    schemas = bundle.get("schemas")
    if not isinstance(schemas, dict):
        raise ValueError("Schema bundle is missing a dictionary 'schemas' entry")
    missing = [model_name for model_name in _REQUIRED_MODELS if model_name not in schemas]
    if missing:
        joined = ", ".join(missing)
        raise ValueError(f"Schema bundle is missing required models: {joined}")


def _dump_json(bundle: dict[str, object]) -> str:
    return json.dumps(bundle, indent=2, sort_keys=True) + "\n"


def build_contract_outputs() -> tuple[dict[str, object], str]:
    bundle = export_schema_bundle()
    _check_bundle_models(bundle)
    engine_types = generate_engine_types(bundle)
    return bundle, engine_types


def write_contract_outputs(
    *,
    project_root: Path,
    schema_path: Path = ENGINE_SCHEMA_PATH,
    engine_types_paths: tuple[Path, ...] = ENGINE_TYPES_PATHS,
) -> tuple[Path, tuple[Path, ...]]:
    bundle, engine_types = build_contract_outputs()
    resolved_schema_path = project_root / schema_path
    _write_text(resolved_schema_path, _dump_json(bundle))
    resolved_ts_paths: list[Path] = []
    for target in engine_types_paths:
        resolved = project_root / target
        _write_text(resolved, engine_types)
        resolved_ts_paths.append(resolved)
    return resolved_schema_path, tuple(resolved_ts_paths)
